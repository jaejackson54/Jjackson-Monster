public class Shape {
    // PROPS - instance variables
    private String type;
    private int sides; 
    private double height;
    private double width; 
    
    // CONSTRUCTOR 
    public Shape(String what, int sides, double height, double width){
        type = what; 
        this.sides = sides; 
        this.height = height; 
        this.width = width; 

    }

    
}
